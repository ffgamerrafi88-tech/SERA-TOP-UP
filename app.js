function openCategory(catName) {
    currentCategory = catName;
    const titleEl = document.getElementById('detail-title');
    const detailImgEl = document.getElementById('detail-category-img');
    
    if(titleEl) titleEl.innerText = catName;
    
    const catInfo = PackagesData[catName] || {};
    
    if(detailImgEl) {
        detailImgEl.src = catInfo.img || 'https://i.ibb.co.com/v4fLwZG1/logo.png';
    }

    selectedPackage = null;
    selectPaymentMethod(selectedPayMethod);

    const grid = document.getElementById('package-grid');
    if(!grid) return;
    grid.innerHTML = '';

    const list = catInfo.packages || [];
    
    const rulesListEl = document.getElementById('dynamic-rules-list');
    if (catInfo.rules && rulesListEl) {
        let rHtml = '';
        catInfo.rules.split('\n').forEach(r => { if(r.trim()) rHtml += `<li>${r}</li>`; });
        rulesListEl.innerHTML = rHtml;
    }

    if(list.length === 0) {
        grid.innerHTML = `<p class="text-xs text-gray-500 col-span-full py-4 text-center">এই ক্যাটাগরিতে বর্তমানে কোনো প্যাকেজ নেই।</p>`;
    } else {
        list.forEach((pkg, index) => {
            const card = document.createElement('div');
            card.id = `pkg-item-${index}`;
            card.className = "p-3.5 border-2 border-gray-200 bg-gray-50 rounded-xl cursor-pointer transition flex flex-col justify-between hover:border-brand-500";
            card.onclick = () => selectPackage(pkg, index, list.length);
            card.innerHTML = `<span class="font-semibold text-xs text-gray-800">${pkg.name}</span><span class="text-brand-600 font-extrabold text-sm mt-1">${pkg.price} TK</span>`;
            grid.appendChild(card);
        });
    }

    selectPaymentType('instant');
    updateCheckoutButtonState();
    navTo('details', true);
}

