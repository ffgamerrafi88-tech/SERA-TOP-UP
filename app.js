function initFirebaseRealtimeSync() {
    db.ref('storeData').on('value', (snapshot) => {
        const data = snapshot.val();
        if (data) {
            if (data.packages) PackagesData = data.packages;
            if (data.payments) PaymentNumbers = data.payments;
            if (data.branding) SiteBranding = data.branding;
            if (data.users) usersStore = data.users;
            if (data.orders) ordersList = data.orders;

            localStorage.setItem('sera_topup_packages', JSON.stringify(PackagesData));
            localStorage.setItem('sera_topup_payments', JSON.stringify(PaymentNumbers));
            localStorage.setItem('sera_topup_branding', JSON.stringify(SiteBranding));
            localStorage.setItem('sera_topup_orders', JSON.stringify(ordersList));
            localStorage.setItem('sera_topup_users', JSON.stringify(usersStore));

            applyBranding();
            renderHomeCategories();
            renderOrdersList();
            checkProfileState();
        }
    }, (error) => {
        console.log("Using local offline storage mode.");
    });
}

