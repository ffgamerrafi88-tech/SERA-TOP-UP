function checkProfileState() {
    const walletHeader = document.getElementById('header-wallet-balance');
    const loggedOutSec = document.getElementById('auth-logged-out');
    const loggedInSec = document.getElementById('auth-logged-in');

    if (currentUser && usersStore[currentUser.email]) {
        currentUser = usersStore[currentUser.email];
    }

    if (currentUser) {
        if(loggedOutSec) loggedOutSec.classList.add('hidden');
        if(loggedInSec) loggedInSec.classList.remove('hidden');
        
        const nameEl = document.getElementById('user-info-name');
        const idEl = document.getElementById('user-info-id');
        const balEl = document.getElementById('user-info-balance');
        const avatarEl = document.getElementById('user-avatar-text');
        const totalOrdEl = document.getElementById('user-total-orders');
        const totalSpendEl = document.getElementById('user-total-spend');

        if(nameEl) nameEl.innerText = currentUser.name;
        if(idEl) idEl.innerText = currentUser.userId;
        if(balEl) balEl.innerText = (currentUser.balance || 0) + " Tk";
        if(walletHeader) walletHeader.innerText = (currentUser.balance || 0) + " ৳";
        if(avatarEl) avatarEl.innerText = currentUser.name.charAt(0).toUpperCase();

        const myOrders = ordersList.filter(o => o.userEmail && o.userEmail.toLowerCase() === currentUser.email.toLowerCase());
        const totalSpendTk = myOrders.reduce((sum, ord) => sum + Number(ord.price), 0);
        if(totalOrdEl) totalOrdEl.innerText = myOrders.length;
        if(totalSpendEl) totalSpendEl.innerText = totalSpendTk + " Tk";
    } else {
        if(loggedOutSec) loggedOutSec.classList.remove('hidden');
        if(loggedInSec) loggedInSec.classList.add('hidden');
        const avatarEl = document.getElementById('user-avatar-text');
        if(avatarEl) avatarEl.innerText = 'S';
        if(walletHeader) walletHeader.innerText = "0 ৳";
    }
}

