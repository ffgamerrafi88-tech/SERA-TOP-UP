async function submitOrder() {
    if (!currentUser) {
        showToast('লগইন প্রয়োজন', 'অর্ডার করতে চাইলে প্রথমে লগইন করুন!', 'error');
        navTo('profile', true);
        return;
    }
    if (currentUser.isBlocked) {
        showToast('অ্যাকাউন্ট ব্লকড', 'আপনার অ্যাকাউন্ট ব্লক করা রয়েছে!', 'error');
        return;
    }
    const playerIdEl = document.getElementById('player-id-input');
    if(!playerIdEl) return;
    const playerId = playerIdEl.value.trim();
    if (!selectedPackage) {
        showToast('সতর্কতা', 'দয়া করে একটি প্যাকেজ সিলেক্ট করুন!', 'error');
        return;
    }
    if (!playerId) {
        showToast('সতর্কতা', 'দয়া করে Player ID কোড লিখুন!', 'error');
        return;
    }

    let payMethodText = "";
    let trxId = "";

    if (selectedPayType === 'wallet') {
        const userBal = Number(currentUser.balance || 0);
        const pkgPrice = Number(selectedPackage.price);
        if (userBal < pkgPrice) {
            showToast('অপর্যাপ্ত ব্যালেন্স', `ওয়ালেটে পর্যাপ্ত টাকা নেই! প্রয়োজন ${pkgPrice} TK`, 'error');
            return;
        }
        currentUser.balance = userBal - pkgPrice;
        if(usersStore[currentUser.email]) {
            usersStore[currentUser.email].balance = currentUser.balance;
        }
        payMethodText = "Wallet Pay";
        trxId = "WALLET_PAY";
    } else {
        const trxInputEl = document.getElementById('trx-id-input');
        if(!trxInputEl) return;
        trxId = trxInputEl.value.trim().toUpperCase();
        if (!trxId || trxId.length < 6) {
            showToast('ট্রানজেকশন আইডি ভুল', 'সঠিক TrxID প্রদান করুন!', 'error');
            return;
        }

        showToast('যাচাই করা হচ্ছে...', 'দয়া করে একটু অপেক্ষা করুন, TrxID ও অ্যামাউন্ট চেক করা হচ্ছে...', 'info');
        
        try {
            const response = await fetch(`/api/receive-sms?action=verify&trxid=${trxId}`);
            const result = await response.json();

            if (!result.valid) {
                showToast('ভুল ট্রানজেকশন আইডি', 'এই TrxID দিয়ে কোনো পেমেন্ট পাওয়া যায়নি! সঠিক TrxID দিন।', 'error');
                return;
            }

            const requiredAmount = Number(selectedPackage.price);
            const smsText = result.sms.msg.toLowerCase();
            const amountMatch = smsText.match(/(?:tk|bdt|taka|৳)\s*([0-9]+(?:\.[0-9]+)?)|([0-9]+(?:\.[0-9]+)?)\s*(?:tk|bdt|taka|৳)/i) || smsText.match(/recieved\s*tk\.?\s*([0-9]+)/i) || smsText.match(/cash\s*in\s*tk\.?\s*([0-9]+)/i);
            
            let detectedAmount = null;
            if (amountMatch) {
                detectedAmount = Number(amountMatch[1] || amountMatch[2]);
            } else {
                const numbers = smsText.match(/\d+/g);
                if(numbers) {
                    for(let numStr of numbers) {
                        let val = Number(numStr);
                        if(val >= requiredAmount) {
                            detectedAmount = val;
                            break;
                        }
                    }
                }
            }

            if (detectedAmount !== null && detectedAmount < requiredAmount) {
                showToast('টাকার পরিমাণ কম', `আপনার পেমেন্টে এসেছে ৳${detectedAmount}, কিন্তু প্যাকেজ মূল্য ৳${requiredAmount}! সঠিক পরিমাণে টাকা পাঠিয়ে আবার চেষ্টা করুন।`, 'error');
                return;
            }

        } catch (err) {
            console.error(err);
        }

        payMethodText = `${selectedPayMethod} (${selectedPayNumber})`;
    }

    const now = new Date();
    const englishDate = now.toLocaleString('en-US', { year: 'numeric', month: 'numeric', day: 'numeric', hour: 'numeric', minute: 'numeric', second: 'numeric', hour12: true });

    const nextSerial = ordersList.length > 0 ? Math.max(...ordersList.map(o => Number(o.serial) || 0)) + 1 : 1;

    const orderObj = {
        serial: nextSerial,
        category: currentCategory,
        package: selectedPackage.name,
        price: selectedPackage.price,
        playerId: playerId,
        payMethod: payMethodText,
        trxId: trxId,
        date: englishDate,
        userEmail: currentUser.email,
        userId: currentUser.userId,
        status: 'Pending'
    };

    ordersList.unshift(orderObj);
    if(usersStore[currentUser.email]) {
        usersStore[currentUser.email] = currentUser;
    }
    saveStoreDataToCloud();

    const telegramMsg = `🚨 *নতুন টপ-আপ অর্ডার (Verified Auto)!*\n\n🔥 *Order:* #${orderObj.serial}\n👤 *User ID:* ${currentUser.userId} (${currentUser.email})\n🎮 *Player ID:* \`${playerId}\`\n📦 *Package:* ${selectedPackage.name}\n💰 *Price:* ৳${selectedPackage.price}\n🔑 *TrxID:* \`${trxId}\``;
    fetch(`https://api.telegram.org/bot${TELEGRAM_TOKEN}/sendMessage?chat_id=${TELEGRAM_CHAT_ID}&text=${encodeURIComponent(telegramMsg)}&parse_mode=Markdown`);

    playerIdEl.value = '';
    const trxInputEl2 = document.getElementById('trx-id-input');
    if(trxInputEl2) trxInputEl2.value = '';

    showToast('অর্ডার সফল!', `আপনার ${selectedPackage.name} পেমেন্ট ভেরিফাই হয়ে অর্ডার জমা হয়েছে।`, 'success');
    navTo('orders', true);
}

